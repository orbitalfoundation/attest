// Build server/blocklist.json: SHA-256 hashes of normalised offensive words, from open word lists read at build time
// (leo-profanity, bad-words, @2toad/profanity in all its languages; dev dependencies only). No word appears in plaintext
// in this repository or on the server. Extra terms the lists miss can be passed once via EXTRA="a,b" (never saved).
//
// Two tiers, chosen from the system dictionary: a word blocks only as a whole handle or a whole hyphen-separated part
// ("exact") unless no ordinary dictionary word contains it, in which case it also blocks anywhere inside a handle.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { normalizeWord, sha } from "../server/blocklist.mjs";
const leo = (await import("leo-profanity")).default; const bw = await import("bad-words"); const { profaneWords } = await import("@2toad/profanity");
const clean = (list) => [...new Set(list.map(normalizeWord).filter((w) => w && w.length >= 3 && w.length <= 30))];
const english = new Set(clean([...leo.list(), ...new bw.Filter().list, ...(profaneWords.get("en") || []), ...(process.env.EXTRA || "").split(",")]));
const other = clean([...profaneWords].filter(([lang]) => lang !== "en").flatMap(([, list]) => list)).filter((w) => !english.has(w));
const dictFile = "/usr/share/dict/words";
const lines = existsSync(dictFile) ? readFileSync(dictFile, "utf8").split("\n").map((w) => w.trim()).filter(Boolean) : [];
const names = new Set(lines.filter((w) => /^[A-Z][a-z]{2,}$/.test(w)).map((w) => w.toLowerCase()));
const dict = [...new Set([...lines.filter((w) => /^[a-z]{3,}$/.test(w)), ...names])];
// A word that is itself a person's or place's name in the dictionary never blocks: real people carry some of these names.
// And a word from another language's list that is an ordinary English word ("name", "flat", "mist", "pour") is dropped.
const englishWords = new Set(lines.filter((w) => /^[a-z]{3,}$/.test(w)));
const words = [...english, ...other.filter((w) => !englishWords.has(w))].filter((w) => !names.has(w));
const set = new Set(words);
const inflected = (d, w) => d === w || [w + "s", w + "es", w + "ed", w + "er", w + "ers", w + "ing", w + "y", w + "ier", w + "iest"].includes(d);
const anywhere = [], exact = [];
for (const w of words) {
  if (w.length < 4 || !english.has(w)) { exact.push(w); continue; }
  const innocent = dict.find((d) => d.includes(w) && !set.has(d) && !inflected(d, w));
  (innocent ? exact : anywhere).push(w);
}
console.log(`names exempted: ${[...english, ...other].filter((w) => names.has(w)).length}; other-language words exact only: ${other.length}`);
const out = { note: "SHA-256 of normalised words (see server/blocklist.mjs). Generated by scripts/build-blocklist.mjs; the words themselves are not stored.",
  generated: new Date().toISOString(), sources: ["leo-profanity", "bad-words", "@2toad/profanity (all languages)"], extraTerms: (process.env.EXTRA || "").split(",").filter(Boolean).length,
  exact: exact.map(sha).sort(), anywhere: anywhere.map(sha).sort() };
writeFileSync(new URL("../server/blocklist.json", import.meta.url), JSON.stringify(out));
console.log(`words ${words.length}: exact ${exact.length}, anywhere ${anywhere.length}; dictionary ${dict.length}`);
